

module dynamic_branch_predictor_top_tb();

    reg         clk;
    reg         rst_n;
    reg  [31:0] fetch_pc;
    wire        predict_taken;
    wire [31:0] next_pc_prediction;

    reg  [31:0] exe_pc;
    reg         predict_taken_old;
    reg         exe_is_branch;
    reg         actual_taken;
    reg  [31:0] actual_target_pc;

    wire        flush_pipeline;
    wire [31:0] corrected_pc;

    // ????? ??????
    initial clk = 0;
    always #10 clk = ~clk;

    // ????? ??? Top Module
    dynamic_branch_predictor_top DUT (
        .clk(clk), .rst_n(rst_n),
        .fetch_pc(fetch_pc), .predict_taken(predict_taken), .next_pc_prediction(next_pc_prediction),
        .exe_pc(exe_pc), .predict_taken_old(predict_taken_old), .exe_is_branch(exe_is_branch),
        .actual_taken(actual_taken), .actual_target_pc(actual_target_pc),
        .flush_pipeline(flush_pipeline), .corrected_pc(corrected_pc)
    );

    initial begin
        $dumpfile("dynamic_branch_predictor_top.vcd");
        $dumpvars;

        // ???? ?????? ????? ???? ??? Fetch ???? Execute ????
        $display("Time | [IF] fetch_pc | pred_tk | next_pc_pred | [EX] exe_pc | act_tk | flush | corr_pc");
        $display("-----------------------------------------------------------------------------------------");
        $monitor("%4d |    %8h   |    %b    |   %8h   |   %8h  |   %b    |   %b   | %8h", 
                 $time, fetch_pc, predict_taken, next_pc_prediction, exe_pc, actual_taken, flush_pipeline, corrected_pc);

        // ??????? ????????
        rst_n = 0; fetch_pc = 32'h0; exe_pc = 32'h0; predict_taken_old = 0;
        exe_is_branch = 0; actual_taken = 0; actual_target_pc = 32'h0;
        #25; rst_n = 1;

        // ?????? ?? Race Condition? ???? ???????? ?????? ??? ???? ?????? ?????? ?????
        
        $display("\n============= CASE 1: First-Time Seen Branch (Missing BTB -> Expect Flush) =============");
        @(posedge clk); #2;
        fetch_pc = 32'h0000_0100; // ????? ??? ????? 100
        // ??????? ?? ??? Fetch: ?????? Not Taken (0) ???? next_pc = 00000104 ??? ??? BTB ????

        @(posedge clk); #2;
        // ???? ??? ??? 100 ???? ??? Execute
        exe_pc            = 32'h0000_0100;
        exe_is_branch     = 1;
        predict_taken_old = 0; // ?????? ?????? ???? ??? ?? ??????? ???? ????
        actual_taken      = 1; // ??? ALU ????? ??? ???? ????!
        actual_target_pc  = 32'h0000_2000; // ??????? ??????? ??????
        
        // ?? ??? ???????? ??? Fetch ???? ??? ??? ???? ????? 104
        fetch_pc = 32'h0000_0104; 

        $display("\n============= CASE 2: Learning & Steady Taken (Hit -> No Flush) =============");
        @(posedge clk); #2;
        // ???? ???? ???? Fetch ???? ??? ??????? (100) ???? ?? ???? ??????
        fetch_pc      = 32'h0000_0100; 
        exe_is_branch = 0; // ???? ??? Execute ??????? ??

        @(posedge clk); #2;
        // ??????? ?? ??????? ??????? ?? ??? pred_tk ???? 1 ???? next_pc ??? ?? 2000 ?????!
        // ???? ??????? ??? Execute ???????
        exe_pc            = 32'h0000_0100;
        exe_is_branch     = 1;
        predict_taken_old = 1; // ?????? ??? Taken
        actual_taken      = 1; // ??????? Taken
        actual_target_pc  = 32'h0000_2000;

        $display("\n============= CASE 3: Loop Termination (Expect Flush) =============");
        @(posedge clk); #2;
        // ??? ????? 100 ?? ??? Fetch ?????? ??? Taken
        fetch_pc = 32'h0000_0100;
        exe_is_branch = 0;

        @(posedge clk); #2;
        // ?? ??? Execute? ???? ????? ??????? ?????? ?? ?????
        exe_pc            = 32'h0000_0100;
        exe_is_branch     = 1;
        predict_taken_old = 1;
        actual_taken      = 0; // Not Taken!
        actual_target_pc  = 32'h0000_2000;

        $display("\n============= CASE 4: Read/Write Hazard (Same Index Collision) =============");
        @(posedge clk); #2;
        // ????? ?????? ?? ??? ?????? ???? ??????? ?????? ????
        fetch_pc          = 32'h0000_0240; 
        exe_pc            = 32'h0000_0240;
        exe_is_branch     = 1;
        predict_taken_old = 0;
        actual_taken      = 1;
        actual_target_pc  = 32'h0000_5000;

        @(posedge clk);
        #40;
        $finish;
    end

endmodule