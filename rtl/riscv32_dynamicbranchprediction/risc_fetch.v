module fetch_prediction_logic (
    input  wire [31:0] fetch_pc,
    
    // ???????? ??????? ?? ?????? ??????? ?????? (BHT & BTB)
    input  wire        predict_taken,       
    input  wire        btb_hit,             // ????? ??? hit ?? ??? BTB
    input  wire [31:0] predicted_target_pc, // ??????? ?????? ???? ??? BTB
    
    output wire        take_branch_decision,
    // ?????? ??????? ???? ????? ??? PC ??????? ???????
    output wire [31:0] next_pc_prediction
